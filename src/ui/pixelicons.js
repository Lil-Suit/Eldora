SPR.luvaD = mirror(SPR.luvaE); SPR.manoplaD = mirror(SPR.manoplaE);
const cache = new Map();

function spriteKey(entry) {
  if (entry.kind === 'equip') {
    if (entry.slot === 'ring') return 'anel';
    if (entry.slot === 'neck') return 'cordao';
    if (SPR[entry.wkind]) return entry.wkind;
    return { shield: 'escudo', weapon: 'espada', helm: 'elmo', legs: 'calca', gloveL: 'luvaE', gloveR: 'luvaD', boots: 'bota', back: 'mochila' }[entry.slot] || 'couro';
  }
  return SPR[entry.id] ? entry.id : null;
}
function spriteOf(entry) {
  const key = spriteKey(entry);
  if (key) return { rows: SPR[key], ck: key, tint: null };
  const m = entry.id && (MATERIALS[entry.id] || QUEST_ITEMS[entry.id]);
  if (m?.sprite && TSPR[m.sprite]) return { rows: TSPR[m.sprite], ck: 't:' + entry.id, tint: m.tint };
  return null;
}

let _iconCanvas = null;
// Gera (e guarda) o ícone como imagem PNG; null se não houver desenho
export function pixelIcon(entry) {
  const sp = spriteOf(entry);
  if (!sp || typeof document === 'undefined') return null;
  const rar = entry.kind === 'equip' ? (entry.rarity || 'comum') : 'comum';
  const th = itemTheme(entry);
  const ck = sp.ck + '|' + rar + (th ? '|' + th.type : '');
  if (cache.has(ck)) return cache.get(ck);
  const rows = sp.rows.trim().split('\n').map((r) => r.trim());
  const pal = { ...BASE, ...(RAR[rar] || RAR.comum) };
  if (sp.tint) { pal.c = sp.tint[0]; pal.C = sp.tint[1]; pal.g = sp.tint[2]; pal.G = sp.tint[3]; }
  // estética do monstro: metal, madeira e couro com as cores dele (a gema segue a raridade)
  if (th) {
    pal.m = th.metal; pal.M = th.metalD; pal.d = th.dark; pal.w = th.fx;
    pal.b = th.wood; pal.B = th.woodD; pal.l = th.wood; pal.L = th.woodD;
    pal.c = mixHex(pal.c, th.metal, 0.55); pal.C = mixHex(pal.C, th.metalD, 0.55);
    pal.o = mixHex(pal.o, th.fx, 0.5); pal.O = mixHex(pal.O, th.fx2, 0.5);
  }
  const S = 18; // 16 + 1px de borda em volta
  // canvas na CPU (willReadFrequently): o toDataURL não precisa esperar a placa de vídeo terminar o quadro
  // (num canvas acelerado ele força a GPU a parar e devolver os pixels — era uma das travadinhas ao cair item)
  const cv = _iconCanvas ||= document.createElement('canvas');
  cv.width = S; cv.height = S;
  const ctx = cv.getContext('2d', { willReadFrequently: true });
  const filled = (x, y) => y >= 0 && y < 16 && x >= 0 && x < 16 && rows[y] && rows[y][x] && rows[y][x] !== '.';
  // borda automática
  ctx.fillStyle = OUTLINE;
  for (let y = -1; y <= 16; y++) for (let x = -1; x <= 16; x++) {
    if (filled(x, y)) continue;
    if (filled(x - 1, y) || filled(x + 1, y) || filled(x, y - 1) || filled(x, y + 1)) ctx.fillRect(x + 1, y + 1, 1, 1);
  }
  for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) {
    const ch = rows[y]?.[x];
    if (!ch || ch === '.') continue;
    ctx.fillStyle = pal[ch] || '#ff00ff';
    ctx.fillRect(x + 1, y + 1, 1, 1);
  }
  if (th) drawMotif(ctx, filled, th);
  const url = cv.toDataURL();
  cache.set(ck, url);
  return url;
}

function mixHex(a, b, t) {
  const pa = parseInt(a.slice(1), 16), pb = parseInt(b.slice(1), 16);
  return '#' + [16, 8, 0].map((sh) => Math.round(((pa >> sh) & 255) * (1 - t) + ((pb >> sh) & 255) * t).toString(16).padStart(2, '0')).join('');
}
// detalhes do monstro desenhados por cima do ícone (pedrinhas, chamas, cristais, espinhos, gotas…)
function drawMotif(ctx, filled, th) {
  const inside = [], top = [], side = [], bottom = [];
  for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) {
    if (filled(x, y)) { if (filled(x - 1, y) && filled(x + 1, y) && filled(x, y - 1) && filled(x, y + 1)) inside.push([x, y]); continue; }
    if (filled(x, y + 1)) top.push([x, y]);
    else if (filled(x - 1, y) || filled(x + 1, y)) side.push([x, y]);
    else if (filled(x, y - 1)) bottom.push([x, y]);
  }
  const pickN = (arr, n) => { const out = []; if (!arr.length) return out; for (let i = 0; i < n; i++) out.push(arr[Math.floor(((i + 0.5) / n) * arr.length)]); return out; };
  const px = (x, y, c) => { if (x < -1 || y < -1 || x > 16 || y > 16) return; ctx.fillStyle = c; ctx.fillRect(x + 1, y + 1, 1, 1); };
  const F = th.fx, F2 = th.fx2;
  const D = th.dark, M2 = th.metalD;
  // desenhos bem visíveis (2–3 px), para dar para ver de longe de que monstro o item veio
  switch (th.motif) {
    case 'pedras': for (const [x, y] of pickN(inside, 4)) { px(x, y, F); px(x + 1, y, F2); px(x, y + 1, F2); px(x + 1, y + 1, D); } for (const [x, y] of pickN(top, 3)) { px(x, y, F2); } break;
    case 'chamas': for (const [x, y] of pickN(top, 6)) { px(x, y, F2); px(x, y - 1, F); px(x, y - 2, '#fff2a0'); } for (const [x, y] of pickN(inside, 2)) px(x, y, F2); break;
    case 'cristais': for (const [x, y] of pickN(side.length ? side : top, 5)) { px(x, y, F); px(x, y - 1, F2); px(x, y + 1, F); } for (const [x, y] of pickN(bottom.length ? bottom : side, 4)) { px(x, y, F2); px(x, y + 1, F); } break;
    case 'espinhos': for (const [x, y] of pickN(side.length ? side : top, 6)) { px(x, y, F); px(x + (x < 8 ? -1 : 1), y, F2); } for (const [x, y] of pickN(top, 3)) { px(x, y, F); px(x, y - 1, F2); } break;
    case 'presas': for (const [x, y] of pickN(top.length ? top : side, 6)) { px(x, y, F2); px(x, y - 1, F); } for (const [x, y] of pickN(side, 4)) { px(x, y, F); px(x, y + 1, '#ffffff'); } break;
    case 'gotas': for (const [x, y] of pickN(bottom.length ? bottom : side, 5)) { px(x, y, F2); px(x, y + 1, F); px(x, y + 2, F2); } for (const [x, y] of pickN(inside, 4)) { px(x, y, F); px(x + 1, y - 1, '#ffffff'); } break;
    case 'folhas': for (const [x, y] of pickN(top.length ? top : side, 5)) { px(x, y, F2); px(x + 1, y - 1, F); px(x - 1, y, F); } for (const [x, y] of pickN(inside, 2)) px(x, y, F); break;
    case 'musgo': for (const [x, y] of pickN(top, 8)) { px(x, y + 1, F2); px(x, y, F); } for (const [x, y] of pickN(inside, 3)) px(x, y, F2); break;
    case 'remendos': for (const [x, y] of pickN(inside, 4)) { px(x, y, F); px(x + 1, y, F); px(x, y + 1, F2); px(x + 1, y + 1, D); } break;
    case 'ambar': for (const [x, y] of pickN(inside, 4)) { px(x, y, F); px(x + 1, y, F2); px(x, y - 1, '#fff2c0'); } break;
    case 'bolhas': for (const [x, y] of [...pickN(inside, 3), ...pickN(side, 4)]) { px(x, y, F); px(x + 1, y - 1, '#ffffff'); } break;
    case 'natal': for (const [x, y] of pickN(inside, 5)) px(x, y, '#ffffff'); for (const [x, y] of pickN(top.length ? top : side, 3)) { px(x, y, F2); px(x + 1, y, F2); px(x, y - 1, F); } break; // flocos brancos + azevinho verde com fruto vermelho
    case 'runas': for (const [x, y] of pickN(inside, 6)) { px(x, y, F); px(x, y - 1, F2); } for (const [x, y] of pickN(side, 3)) px(x, y, F); break;
    default: for (const [x, y] of pickN(inside, 5)) { px(x, y, F2); px(x + 1, y, M2); } break;
  }
}

export function pixelIconHtml(entry, cls = 'px') {
  const u = pixelIcon(entry);
  return u ? `<img class="${cls}" src="${u}" alt="" draggable="false">` : null;
}
